"""Build evals/README.md from every registered method's evaluations.

    python scripts/report.py            # after evals have been run with scripts/eval_method.py

Per walker: the Stage 0 gate (A walk, B resist 25% body weight, C push 15 kg).
Per push policy and suite: success by object group and mass, fall rate, and (Stage 2) the
three weakest shapes at 10-25 kg on training-range sizes.
"""

from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from methods import EVALS, load  # noqa: E402


def f2(x) -> str:
    return "" if x is None else f"{x:.2f}"


def walker_rows(mid: str, m: dict) -> list[str]:
    rows = []
    for suite_dir in sorted((EVALS / mid / "eval").glob("*")):
        v = suite_dir / "validation.json"
        if not v.exists():
            continue
        d = json.loads(v.read_text())
        r = d["results"]
        a, b, c = r.get("A", {}), r.get("B", {}), r.get("C", {})
        rows.append(f"| {mid} | {m.get('note', '')} | {a.get('fall_rate', 0):.1%} / {a.get('vx_error', 0):.2f} | "
                    f"{b.get('fall_rate', 0):.1%} / {b.get('vx_kept', 0):.0%} | "
                    f"{c.get('fall_rate', 0):.1%} / {c.get('box_disp_median', 0):.2f} m | "
                    f"{'PASS' if d.get('passed') else 'fail'} |")
    return rows


def light_weak(csv_path: Path) -> str:
    if not csv_path.exists():
        return ""
    g = defaultdict(list)
    for r in csv.DictReader(open(csv_path)):
        if r.get("condition", "normal") == "normal" and r.get("size_set", "in") == "in" and float(r["mass"]) <= 25:
            g[r["object"]].append(int(r.get("success", r.get("success_strict", 0))))
    s = sorted((sum(v) / len(v), o) for o, v in g.items())
    return ", ".join(f"{o} {x:.2f}" for x, o in s[:3])


def push_rows(mid: str, m: dict) -> list[str]:
    rows = []
    for suite_dir in sorted((EVALS / mid / "eval").glob("*")):
        sj = suite_dir / "summary.json"
        if not sj.exists():
            continue
        d = json.loads(sj.read_text())
        if "by_group_mass" in d:  # Stage 2 eval
            def cell(group, mass):
                v = d["by_group_mass"].get(f"{group} / {mass} kg", {}).get("normal")
                return f2(v["success"]) if v else ""
            ov = d.get("overall_normal") or {}
            rows.append(f"| {mid} | {suite_dir.name} | {cell('seen', 10)} / {cell('seen', 25)} / {cell('seen', 40)} | "
                        f"{cell('unseen', 10)} / {cell('unseen', 25)} / {cell('unseen', 40)} | "
                        f"{f2(ov.get('success'))} | {f2(ov.get('fell'))} | {light_weak(suite_dir / 'episodes.csv')} |")
        else:  # Stage 1b/1c eval_push
            bm = d.get("by_mass", {})
            ms = sorted(bm, key=float)
            succ = " / ".join(f2(bm[k]["success"]) for k in ms)
            ov = d.get("overall", {})
            rows.append(f"| {mid} | {suite_dir.name} | {succ} (masses {', '.join(f'{float(k):g}' for k in ms)}) | | "
                        f"{f2(ov.get('success'))} | {f2(ov.get('fell'))} | |")
    return rows


def pair_rows() -> list[str]:
    """Two-robot (and solo) evaluations from scripts/eval_coop2.py: evals/<name>/eval/pair/."""
    found = sorted(EVALS.glob("*/eval/pair/summary.json"))
    if not found:
        return []
    out = ["", "## Two robots (scripts/eval_coop2.py)", "",
           "Same fixed tasks for every policy (12 objects x 4 scenarios, nominal sizes); success = 10 cm / 6 deg "
           "held 1 s within 80 s. Cells: success (ANYmal falls / Spot falls).", ""]
    data = [(f, json.loads(f.read_text())) for f in found]
    masses = sorted({f"{float(m):g}" for _, d in data for m in d.get("masses", [])}, key=float)
    rows = []
    for f, d in data:
        cells = []
        for m in masses:
            s = d["by_mass"].get(m) or {}
            cells.append(f"{f2(s.get('success'))} ({f2(s.get('fell_anymal'))} / {f2(s.get('fell_spot'))})" if s else "")
        rows.append(f"| {f.parents[2].name} | {d.get('policy', '')} | " + " | ".join(cells) + " |")
    out += ["| name | policy | " + " | ".join(f"{m} kg" for m in masses) + " |", "|---|---|" + "---|" * len(masses)]
    return out + rows


def main() -> int:
    reg = load()
    lines = ["# Evaluations", "",
             "Generated by `scripts/report.py` from `evals/<method>/eval/<suite>/`. Methods and their "
             "checkpoints are listed in `evals/registry.yaml` (checkpoints and eval videos stay on the "
             "cluster under `logs/evals/<method>/`); run a suite with "
             "`ID=<method> SUITE=<suite> sbatch slurm/eval_method.sbatch`.", "",
             "## Methods", "", "| id | stage | task | walker | source | note |", "|---|---|---|---|---|---|"]
    for mid, m in reg.items():
        lines.append(f"| {mid} | {m['stage']} | {m['task']} | {m.get('walker', '')} | `{m['source']}` | {m.get('note', '')} |")
    lines += ["", "## Walkers (Stage 0 gate)", "",
              "| id | note | A walk: falls / vx err | B resist: falls / speed kept | C push 15 kg: falls / moved | gate |",
              "|---|---|---|---|---|---|"]
    for mid, m in reg.items():
        if m["stage"] == "walker":
            lines += walker_rows(mid, m)
    lines += ["", "## Push policies", "",
              "Success: held at the goal (suite's tolerance). Seen / unseen shapes at 10 / 25 / 40 kg, "
              "training-range sizes for Stage 2.", "",
              "| id | suite | seen 10/25/40 kg | unseen 10/25/40 kg | overall | fell | weakest shapes at 10-25 kg |",
              "|---|---|---|---|---|---|---|"]
    for mid, m in reg.items():
        if m["stage"] != "walker":
            lines += push_rows(mid, m)
    lines += pair_rows()
    (EVALS / "README.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
